    private void populateTable() {
        DefaultTableModel model = (DefaultTableModel) tblEnterpriseAdmin.getModel();
        model.setRowCount(0);
        rowAccounts.clear();
        for (Network network : system.getNetworkList()) {
            for (Enterprise enterprise : network.getEnterpriseDirectory().getEnterpriseList()) {
                for (UserAccount userAccount : enterprise.getUserAccountDirectory().getUserAccountList()) {
                    model.addRow(new Object[]{enterprise.getName(), network.getName(), userAccount.getUsername()});
                    rowAccounts.add(userAccount);
                }
            }
        }
    }

    private void populateNetworkComboBox() {
        cmbNetwork.removeAllItems();
        for (Network network : system.getNetworkList()) {
            cmbNetwork.addItem(network);
        }
    }

    private void populateEnterpriseComboBox(Network network) {
        cmbEnterprise.removeAllItems();
        if (network == null) {
            return;
        }
        for (Enterprise enterprise : network.getEnterpriseDirectory().getEnterpriseList()) {
            cmbEnterprise.addItem(enterprise);
        }
    }

    // Picks the correct Enterprise Admin role subclass based on enterprise type
    private Role adminRoleFor(Enterprise enterprise) {
        switch (enterprise.getEnterpriseType()) {
            case MANUFACTURER:
                return new ManufacturerEnterpriseAdminRole();
            case WHOLESALER:
                return new WholesalerEnterpriseAdminRole();
            case RETAILER:
                return new RetailerEnterpriseAdminRole();
            default:
                return null;
        }
    }

    private UserAccount getSelectedAccount() {
        int row = tblEnterpriseAdmin.getSelectedRow();
        if (row < 0 || row >= rowAccounts.size()) {
            JOptionPane.showMessageDialog(this, "Select an account first.");
            return null;
        }
        return rowAccounts.get(row);
    }
