    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        UserAccount account = getSelectedAccount();
        if (account == null) {
            return;
        }
        for (Network network : system.getNetworkList()) {
            for (Enterprise enterprise : network.getEnterpriseDirectory().getEnterpriseList()) {
                if (enterprise.getUserAccountDirectory().getUserAccountList().contains(account)) {
                    enterprise.getUserAccountDirectory().getUserAccountList().remove(account);
                    enterprise.getEmployeeDirectory().getEmployeeList().remove(account.getEmployee());
                }
            }
        }
        populateTable();
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed

        Enterprise enterprise = (Enterprise) cmbEnterprise.getSelectedItem();
        if (enterprise == null) {
            JOptionPane.showMessageDialog(this, "Select a network and enterprise first.");
            return;
        }
        String username = txtUsername.getText().trim();
        String password = String.valueOf(txtPassword.getPassword());
        String name = txtName.getText().trim();
        if (username.isEmpty() || password.isEmpty() || name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields are required.");
            return;
        }
        if (!enterprise.getUserAccountDirectory().checkIfUsernameIsUnique(username)) {
            JOptionPane.showMessageDialog(this, "That username is already taken.");
            return;
        }

        Employee employee = enterprise.getEmployeeDirectory().createEmployee(name);
        enterprise.getUserAccountDirectory().createUserAccount(username, password, employee, adminRoleFor(enterprise));
        populateTable();
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:

        UserAccount account = getSelectedAccount();
        if (account == null) {
            return;
        }
        String username = txtUsername.getText().trim();
        String password = String.valueOf(txtPassword.getPassword());
        String name = txtName.getText().trim();
        if (username.isEmpty() || password.isEmpty() || name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields are required.");
            return;
        }
        account.setUsername(username);
        account.setPassword(password);
        account.getEmployee().setName(name);
        populateTable();
    }//GEN-LAST:event_btnUpdateActionPerformed

