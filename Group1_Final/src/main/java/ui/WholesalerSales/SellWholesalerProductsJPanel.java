    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        // TODO add your handling code here:

        int selectedRowIndex = tblProductCatalog.getSelectedRow();
        if(selectedRowIndex < 0){
            JOptionPane.showMessageDialog(this, "Please select product");
            return;
        }
        Product product = (Product) tblProductCatalog.getValueAt(selectedRowIndex, 0);
        int quant = 0;
        quant = (Integer)spnQuantity.getValue();
        double price = 0.0;
        price = product.getPrice();
        OrderItem item = currentOrder.findProduct(product);
        if (item == null){
            if(product.getAvail() >= quant){
                currentOrder.addNewOrderItem(product,price, quant);
                product.setAvail(product.getAvail()- quant);

            }else{
                JOptionPane.showMessageDialog(this,"Quantity cannot be more than availability");
                return;
            }
        }else{
            int oldQuant = item.getQuantity();
            if(item.getProduct().getAvail()+ oldQuant < quant){
                JOptionPane.showMessageDialog(this,"Quantity cannot be more than availability");
                return;
            }
            item.getProduct().setAvail(item.getProduct().getAvail()+oldQuant-quant);
            item.setQuantity(quant);
        }
        populateProductTable();
        populateCartTable();
    }//GEN-LAST:event_btnAddToCartActionPerformed
    private void populateProductTable() {
 
        DefaultTableModel model = (DefaultTableModel) tblProductCatalog.getModel();
        model.setRowCount(0);
        
        for (Product p : productCatalog.getProductcatalog()) {
            Object row[] = new Object[4];
            row[0] = p;
            row[1] = p.getModelNumber();
            row[2] = p.getPrice();
            row[3] = p.getAvail();
            model.addRow(row);
        }
        
    }
    private void populateProductTable(String keyword) {
        DefaultTableModel model = (DefaultTableModel) tblProductCatalog.getModel();
        model.setRowCount(0);
        for (Product p : productCatalog.getProductcatalog()){ 
            if(p.getProdName().equalsIgnoreCase(keyword)){
                Object row[] = new Object[4];
                row[0] = p;
                row[1] = p.getModelNumber();
                row[2] = p.getPrice();
                row[3] = p.getAvail();
                model.addRow(row);
            }
        }
    }
    private void populateCartTable() {
        
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
        model.setRowCount(0);
        
        for (OrderItem p : currentOrder.getOrderItemList()) {
            Object row[] = new Object[4];
            row[0] = p;
            row[1] = p.getProduct().getPrice();
            row[2] = p.getQuantity();
            row[3] = p.getProduct().getPrice()*p.getQuantity();
            model.addRow(row);
        }
    }

